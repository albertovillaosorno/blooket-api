class Control {
  id = "";
  value = "";
  tagName = "INPUT";
  type = "text";
  disabled = false;
  readOnly = false;
  maxLength = -1;
  checked = true;
  isConnected = true;
  textContent = "";
  parentElement: Control | undefined;
  attributes: Record<string, string> = {};
  selectors: Record<string, Control[]> = {};
  onEvent = (_event: Event): void => {};
  onClick = (): void => {};
  clicked = 0;
  getAttribute(name: string): string | null {
    return this.attributes[name] ?? null;
  }
  getBoundingClientRect() { return { width: 100, height: 30 }; }
  querySelectorAll(selector: string) { return this.selectors[selector] ?? []; }
  querySelector(selector: string) {
    return this.querySelectorAll(selector)[0] ?? null;
  }
  closest() { return this.parentElement; }
  dispatchEvent(event: Event) { this.onEvent(event); return true; }
  click() { this.clicked++; this.onClick(); }
}

async function withEditor(
  run: (page: ReturnType<typeof editor>) => Promise<void>,
  kind: "typing" | "mc" = "typing",
): Promise<void> {
  const page = editor(kind);
  const names = ["document", "location", "HTMLInputElement",
    "HTMLTextAreaElement", "getComputedStyle",
    "__blooketAddQuestionFormWatch"] as const;
  const before = names.map(name =>
    Object.getOwnPropertyDescriptor(globalThis, name));
  class NativeControl {}
  Object.defineProperty(NativeControl.prototype, "value", {
    set(this: Control, value: string) { this.value = value; },
  });
  const values = [page.document,
    new URL("https://dashboard.blooket.com/edit?id=set-fixture"),
    NativeControl, NativeControl,
    () => ({ display: "block", visibility: "visible" }), page.watch];
  names.forEach((name, index) => Object.defineProperty(globalThis, name,
    { configurable: true, value: values[index] }));
  try { await run(page); }
  finally {
    names.forEach((name, index) => {
      if (before[index])
        Object.defineProperty(globalThis, name, before[index]!);
      else Reflect.deleteProperty(globalThis, name);
    });
  }
}

function editor(kind: "typing" | "mc" = "typing") {
  const form = new Control();
  form.tagName = "FORM";
  const hidden = new Control();
  hidden.type = "hidden";
  hidden.parentElement = form;
  const document = new Control() as Control & {
    getElementById: (id: string) => Control | null;
  };
  document.getElementById = id => id === "types" ? list : null;
  const watch = { document, setId: "set-fixture", form, question: hidden,
    prepared: false, submitted: false, dirty: false,
    controlsPrepared: false };
  const prompt = new Control();
  prompt.tagName = "TEXTAREA";
  const time = new Control();
  time.type = "number";
  time.value = "20";
  const picker = new Control();
  picker.tagName = "DIV";
  picker.attributes["aria-controls"] = "types";
  const list = new Control();
  const typing = new Control();
  typing.textContent = "Typing Answer";
  const mc = new Control();
  mc.textContent = "Multiple Choice";
  list.selectors['[role="option"]'] = [mc, typing];
  const answers: Control[] = [];
  const modes: string[] = [];
  const selected: boolean[] = [];
  let qType = "mc";
  let number = 1;
  let providerImage = "";
  let random = true;
  let ignored = false;
  let extraProviderField = false;
  let hiddenWrites = 0;
  let mcAnswerLength = 0;
  let mcTrailingEmptyEvents = 0;
  let serialized = "";
  const render = () => {
    if (ignored) return;
    // Recovered Edit client module 89770 renders four visible answer slots,
    // but its onChange assigns only the touched slot to the answers array.
    const savedAnswers = qType === "mc"
      ? answers.slice(0, mcAnswerLength) : answers;
    serialized = JSON.stringify({
      number, question: prompt.value,
      answers: savedAnswers.map(answer => answer.value),
      correctAnswers: savedAnswers.filter((answer, index) =>
        qType === "typing" || selected[index]).map(answer => answer.value),
      image: providerImage, audio: "", qType, random,
      answerTypes: qType === "typing" ? [...modes] : null,
      timeLimit: Number(time.value),
      ...(extraProviderField ? { providerExtra: true } : {}),
    });
  };
  Object.defineProperty(hidden, "value", {
    get: () => serialized,
    set: () => { hiddenWrites++; throw Error("hidden-field-override"); },
  });
  const addAnswer = () => {
    const answer = new Control();
    const parent = new Control();
    const match = new Control();
    match.textContent = "Is Exactly";
    parent.selectors["button"] = [match];
    answer.parentElement = parent;
    const index = answers.length;
    answers.push(answer);
    modes.push("exactly");
    match.onClick = () => {
      modes[index] = modes[index] === "exactly" ? "contains" : "exactly";
      match.textContent = modes[index] === "exactly"
        ? "Is Exactly" : "Contains";
      render();
    };
    answer.onEvent = () => {
      if (qType === "mc") {
        mcAnswerLength = Math.max(mcAnswerLength, index + 1);
        if (index >= 2 && answer.value === "") mcTrailingEmptyEvents++;
      }
      render();
    };
    form.selectors['input[name="accepted-answers"]'] = answers;
  };
  typing.onClick = () => {
    qType = "typing";
    answers.length = 0;
    modes.length = 0;
    selected.length = 0;
    addAnswer();
    render();
  };
  const alternative = new Control();
  alternative.textContent = "Add Alternative Answer";
  alternative.onClick = () => { addAnswer(); render(); };
  form.selectors["button"] = [alternative];
  form.selectors['[role="combobox"]'] = [picker];
  if (kind === "mc") {
    for (let index = 0; index < 4; index++) {
      addAnswer();
      const answer = answers[index]!;
      answer.tagName = "TEXTAREA";
      answer.id = "answer-" + index;
      form.selectors["textarea#answer-" + index] = [answer];
      selected.push(false);
      const button = new Control();
      button.tagName = "BUTTON";
      button.onClick = () => { selected[index] = !selected[index]; render(); };
      form.selectors['button[aria-label="Mark Answer ' +
        (index + 1) + ' as Correct"]'] = [button];
    }
    form.selectors['textarea[id^="answer-"]'] = answers;
    const shuffle = new Control();
    shuffle.type = "checkbox";
    shuffle.checked = true;
    shuffle.onClick = () => {
      shuffle.checked = !shuffle.checked;
      random = shuffle.checked;
      render();
    };
    form.selectors["input#shuffle-toggle"] = [shuffle];
  }
  form.selectors["textarea#question"] = [prompt];
  form.selectors["input#time-limit"] = [time];
  prompt.onEvent = () => { render(); };
  time.onEvent = () => { render(); };
  render();
  const delayTypingEvents = () => {
    const original = typing.onClick;
    typing.onClick = () => {
      original();
      const queued = (patch: (state: Record<string, unknown>) => void) => {
        const prior = JSON.parse(serialized) as Record<string, unknown>;
        patch(prior);
        setTimeout(() => { serialized = JSON.stringify(prior); }, 40);
      };
      prompt.onEvent = () => queued(state => {
        state["question"] = prompt.value;
      });
      time.onEvent = () => queued(state => {
        state["timeLimit"] = Number(time.value);
      });
      const accepted = answers[0]!;
      accepted.onEvent = () => queued(state => {
        state["answers"] = [accepted.value];
        state["correctAnswers"] = [accepted.value];
      });
      const mode = accepted.parentElement!.selectors["button"]![0]!;
      mode.onClick = () => queued(state => {
        const next = mode.textContent === "Is Exactly"
          ? "contains" : "exactly";
        mode.textContent = next === "exactly" ? "Is Exactly" : "Contains";
        state["answerTypes"] = [next];
      });
    };
  };
  const delayMcEvents = () => {
    // In React, two synthetic input events in one turn may read an old
    // captured question object. The last asynchronous state update wins.
    const queued = (patch: (old: Record<string, unknown>) => void) => {
      const prior = JSON.parse(serialized) as Record<string, unknown>;
      patch(prior);
      setTimeout(() => { serialized = JSON.stringify(prior); }, 40);
    };
    prompt.onEvent = () => queued(record => {
      record["question"] = prompt.value;
    });
    time.onEvent = () => queued(record => {
      record["timeLimit"] = Number(time.value);
    });
    for (let index = 0; index < 4; index++) {
      const answer = answers[index]!;
      answer.onEvent = () => queued(record => {
        const copied = [...record["answers"] as string[]];
        copied[index] = answer.value;
        record["answers"] = copied;
      });
      const correct = form.selectors['button[aria-label="Mark Answer ' +
        (index + 1) + ' as Correct"]']![0]!;
      correct.onClick = () => queued(record => {
        selected[index] = !selected[index];
        const current = record["correctAnswers"] as string[];
        record["correctAnswers"] = selected[index]
          ? [...current, answer.value]
          : current.filter(value => value !== answer.value);
      });
    }
  };
  return { document, form, hidden, watch, prompt, time, picker, list,
    delayMcEvents, delayTypingEvents,
    render, hiddenWrites: () => hiddenWrites,
    mcTrailingEmptyEvents: () => mcTrailingEmptyEvents,
    ignoreChanges: () => { ignored = true; },
    driftProviderShape: () => { extraProviderField = true; render(); },
    driftQuestionNumber: () => { number = 2; render(); },
    driftProviderImage: () => { providerImage = "owned-media"; render(); },
    addSerializedTrailingAnswer: () => {
      const native = JSON.parse(serialized) as Record<string, unknown>;
      (native["answers"] as string[])[3] = "Unexpected provider answer";
      serialized = JSON.stringify(native);
    },
    clearGenerated: () => { serialized = ""; } };
}

test("visible editor events generate typing state without hidden overrides",
  async () => withEditor(async page => {
    const serialized = Function("return (" +
      prepareBlooketQuestionControls.toString() + ")")() as
      typeof prepareBlooketQuestionControls;
    assert.equal(await serialized(input), true);
    assert.equal(page.prompt.value, input.question);
    assert.equal(page.time.value, "15");
    assert.equal(page.watch.controlsPrepared, true);
    assert.equal(page.hiddenWrites(), 0);
    const beforeSave = page.hidden.value;
    // The provider's submit rerender now retains actual editor state.
    page.render();
    assert.equal(page.hidden.value, beforeSave);
    const saved = JSON.parse(page.hidden.value);
    assert.equal(saved.qType, "typing");
    assert.deepEqual(saved.answers, ["sun"]);
    assert.deepEqual(saved.answerTypes, ["contains"]);
    assert.equal(await serialized(input), false);
  }));

